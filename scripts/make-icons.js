// Builds public/icons.js: the app's UI icons, taken from Lucide (node_modules/lucide-static) so they all share one
// style, plus the Graphite mark (an isometric graphite crystal drawn as a graph) for the graph view.
// Run after changing the list: node scripts/make-icons.js
const fs = require('fs');
const path = require('path');

const LUCIDE = path.join(__dirname, '..', 'node_modules', 'lucide-static', 'icons');
const inner = name => {
  const svg = fs.readFileSync(path.join(LUCIDE, name + '.svg'), 'utf8');
  return svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>')).replace(/\s*\n\s*/g, '').replace(/\s*\/>/g, '/>');
};
// The Graphite mark: a hexagon (graphite's crystal cell) seen as a cube, with a node at its centre.
const GRAPHITE = '<path d="M12 3.2 19.6 7.6v8.8L12 20.8 4.4 16.4V7.6z"/><path d="M12 12 4.4 7.6M12 12l7.6-4.4M12 12v8.8"/><circle cx="12" cy="12" r="1.7" fill="currentColor"/>';

const sets = {
  ICON: {
    folder: 'folder', search: 'search', tag: 'tag', graph: GRAPHITE, calendar: 'calendar-days', terminal: 'square-terminal',
    switcher: 'file-search', filePlus: 'file-plus', folderPlus: 'folder-plus', collapse: 'chevrons-down-up', moon: 'moon',
    sidebarLeft: 'panel-left', sidebarRight: 'panel-right', chev: 'chevron-right', back: 'arrow-left', forward: 'arrow-right',
    dice: 'dice-5', link: 'link', list: 'list', globe: 'languages', download: 'download', brain: 'brain', wand: 'wand-sparkles',
    spellcheck: 'spell-check', cap: 'graduation-cap', help: 'circle-help', gear: 'settings',
  },
  TAB_ICON: {
    note: 'file-text', pdf: 'book-open-text', image: 'file-image', media: 'file-video', file: 'file', graph: GRAPHITE,
    help: 'circle-help', review: 'brain', empty: 'square-dashed',
  },
  SEL_ICON: { note: 'notebook-pen', spark: 'sparkles', help: 'circle-help', bulb: 'lightbulb', copy: 'copy' },
};

let out = '// Generated by scripts/make-icons.js from Lucide icons (ISC licence, https://lucide.dev). Do not edit by hand.\n';
for (const [set, map] of Object.entries(sets)) {
  out += `export const ${set} = {\n`;
  for (const [key, src] of Object.entries(map)) out += `  ${key}: ${JSON.stringify(src.startsWith('<') ? src : inner(src))},\n`;
  out += '};\n';
}
out += `export const GRAPHITE_MARK = ${JSON.stringify(GRAPHITE)};\n`;
fs.writeFileSync(path.join(__dirname, '..', 'public', 'icons.js'), out);
console.log('public/icons.js written');
